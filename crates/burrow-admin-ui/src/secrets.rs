#[derive(Debug, Clone, PartialEq)]
pub struct Row {
    pub fp: String,
    pub source: String,
    pub fresh: bool,
    pub unset: bool,
}

pub fn rows(v: Option<&Value>) -> Vec<Row> {
    burrow_admin_proto::value::one_or_many(v)
        .iter()
        .filter_map(|i| {
            if let Some((_, fp)) = as_new_secret(i) {
                return Some(Row {
                    fp,
                    source: "new · generated by the server".into(),
                    fresh: true,
                    unset: false,
                });
            }
            let s = as_secret(i)?;
            Some(Row {
                fp: s.fp.clone().unwrap_or_default(),
                source: match &s.src {
                    SecretSrc::Literal => "in server.yaml".into(),
                    SecretSrc::Env(e) => format!("env: {e}"),
                },
                fresh: false,
                unset: s.unset || s.fp.is_none(),
            })
        })
        .collect()
}

fn in_use_fp(section: &str, name: &str) -> Option<String> {
    if section != ClientEntry::section() {
        return None;
    }
    store().state.with(|s| {
        s.as_ref()
            .and_then(|s| s.runtime.sessions.get(name))
            .map(|x| x.secret_fp.clone())
    })
}

pub fn secret_list(path: Path, id: String, max: u32) -> AnyView {
    let s = store();
    let e = s.edit;
    let section = path.first().cloned().unwrap_or_default();
    let name = path.get(1).cloned().unwrap_or_default();
    let schema_path = format!("{section}/*/{}", path.get(2).cloned().unwrap_or_default());
    let p2 = path.clone();
    let list = Memo::new(move |_| rows(e.value(&p2).as_ref()));
    let (sec2, name2) = (section.clone(), name.clone());
    let in_use = Signal::derive(move || in_use_fp(&sec2, &name2));
    let p3 = path.clone();
    let add = move |_| {
        let p = p3.clone();
        api::request(msg::req::GENERATE_SECRET, json!({}), move |r| {
            if let Ok(Ok(g)) = r.map(serde_json::from_value::<GeneratedSecret>) {
                e.add_secret(&p, &g.handle, &g.fp);
                added_outside_edit(s, &p);
            }
        });
    };
    let full = Signal::derive(move || list.with(|l| l.len() as u32 >= max.max(1)));
    let p5 = path.clone();
    let granting = Signal::derive(move || {
        let mut secrets = burrow_admin_proto::value::one_or_many(e.value(&p5).as_ref());
        secrets.push(new_secret("", ""));
        crate::grants::refuses(&p5, Some(&Value::Array(secrets)))
    });
    let label = Signal::derive(move || {
        if list.with(Vec::is_empty) {
            "Generate a secret".to_string()
        } else {
            "Rotate secret".to_string()
        }
    });
    let can = s.can_write_now();
    let what = if section == ClientEntry::section() {
        ClientEntry::ENTITY
    } else {
        VisitorEntry::ENTITY
    };
    let p4 = path.clone();
    let body = move || {
        let used = in_use.get();
        let known = section == ClientEntry::section();
        list.get()
            .into_iter()
            .map(|r| {
                let fp = r.fp.clone();
                let using = used.as_deref() == Some(fp.as_str());
                let p = p4.clone();
                let only_one = list.with(|l| l.len() == 1);
                let state = if r.fresh {
                    view! { <span class=tag_class(Tone::Accent)>"new · shown once after apply"</span> }.into_any()
                } else if using {
                    view! { <span class=tag_class(Tone::Success) data-testid="in-use"><burrow_ui_kit::Icon name="check" small=true/>"in use by the session"</span> }.into_any()
                } else if known && used.is_some() {
                    view! { <span class=tag_class(Tone::Neutral)>"not in use · safe to remove"</span> }.into_any()
                } else {
                    view! { <span class="text-text-faint">"—"</span> }.into_any()
                };
                view! {
                    <li class="grid grid-cols-[minmax(0,1fr)_minmax(0,1.2fr)_minmax(0,1.4fr)_auto] items-center gap-4 border-b border-rowline px-4 py-3 last:border-b-0" data-fp=fp.clone() data-in-use=using.then_some("true")>
                        <span class="flex items-center gap-2 font-mono text-[13px]"><burrow_ui_kit::Icon name="passkey" small=true/>{fp.clone()}</span>
                        <span class=if r.source.starts_with("env:") { "font-mono text-[13px]" } else { "text-[13px]" }>
                            {r.source.clone()}
                            {r.unset.then(|| view! { <span class="ml-2 text-danger">"not set in the environment"</span> })}
                        </span>
                        <span>{state}</span>
                        <span class="text-right">
                            {(can && !only_one).then(|| {
                                let fp = fp.clone();
                                view! {
                                    <button
                                        type="button"
                                        class="inline-flex cursor-pointer items-center gap-1 text-[13px] font-semibold text-danger hover:underline disabled:cursor-not-allowed disabled:text-text-faint disabled:no-underline"
                                        data-testid="remove-secret"
                                        disabled=using
                                        title=using.then_some("The connected session uses this secret. Rotate first, then remove it once the client uses the new one.")
                                        aria-label=format!("Remove secret {fp}")
                                        on:click=move |_| {
                                            e.remove_secret(&p, &fp);
                                            added_outside_edit(s, &p);
                                        }
                                    >
                                        <burrow_ui_kit::Icon name="trash" small=true/>
                                        "Remove"
                                    </button>
                                }
                            })}
                        </span>
                    </li>
                }
            })
            .collect_view()
    };
    let note = move || {
        let n = list.with(Vec::len);
        if n > 1 {
            format!(
                "A {what} may have at most {max} secrets. Remove the old one once the {what} uses the new one."
            )
        } else {
            format!(
                "Secret values are never shown here. A new one is shown once, after Apply. At most {max} per {what}."
            )
        }
    };
    view! {
        <section id=id class="mb-4 rounded-card border border-border bg-surface" data-testid="secrets" data-schema=schema_path>
            <div class="flex items-center gap-3 border-b border-border px-4 py-3">
                <h2 class="text-[13.5px] font-bold">"Secrets"</h2>
                <span class="ml-auto"></span>
                {can.then(|| view! {
                    <Button
                        label=label
                        variant="tinted"
                        small=true
                        icon="refresh"
                        testid="rotate"
                        disabled=Signal::derive(move || full.get() || granting.get())
                        reason=Signal::derive(move || if granting.get() { IN_THE_FILE.to_string() } else if full.get() { format!("A {what} may have at most {max} secrets.") } else { String::new() })
                        on_click=add
                    />
                })}
            </div>
            <div class="grid grid-cols-[minmax(0,1fr)_minmax(0,1.2fr)_minmax(0,1.4fr)_auto] gap-4 border-b border-border px-4 py-[9px] text-[11px] font-bold tracking-[0.07em] text-text-faint uppercase" aria-hidden="true">
                <span>"Fingerprint"</span><span>"Source"</span><span>"Session"</span><span></span>
            </div>
            <ul>{body}</ul>
            {move || granting.get().then(|| view! { <div class="border-t border-border px-4 pb-1.5">{crate::grants::in_the_file()}</div> })}
            <p class="border-t border-border px-4 py-3 text-[12.5px] text-text-muted">{note}</p>
        </section>
    }
    .into_any()
}

fn os_now() -> String {
    let ua = window()
        .navigator()
        .user_agent()
        .unwrap_or_default()
        .to_lowercase();
    if ua.contains("windows") {
        "windows".into()
    } else if ua.contains("mac os") {
        "macos".into()
    } else {
        "linux".into()
    }
}

const RELEASES: &str = "https://github.com/CharlesNg35/burrow/releases/latest";

fn os_label(os: &str) -> &'static str {
    match os {
        "windows" => "Windows",
        "macos" => "macOS",
        _ => "Linux",
    }
}

#[component]
pub fn SnippetView(
    sn: Snippets,
    #[prop(optional)] secret: Option<String>,
    #[prop(optional)] children: Option<Children>,
) -> impl IntoView {
    let tab: RwSignal<&'static str> = RwSignal::new("commands");
    let os = RwSignal::new(os_now());
    let commands = sn.commands.clone();
    let has_init = commands.iter().any(|c| c.line.contains("burrow init"));
    let commands_text = Signal::derive(move || {
        let o = os.get();
        commands
            .iter()
            .filter(|c| c.os == o)
            .map(|c| format!("# {}\n$ {}", c.label, c.line))
            .collect::<Vec<_>>()
            .join("\n")
    });
    let export = match &secret {
        Some(v) => format!("export {}='{v}'", sn.env_var),
        None => format!("export {}='…'", sn.env_var),
    };
    let ps = match &secret {
        Some(v) => format!("$env:{} = '{v}'", sn.env_var),
        None => format!("$env:{} = '…'", sn.env_var),
    };
    let config = sn.config.clone();
    let file = sn.file_name.clone();
    let env_config = sn.env_config.clone();
    let kind = sn.kind.clone();
    let asks = children.is_some();
    let unknown = (!sn.server_known).then(|| {
        view! {
            <div class="mb-3">
                <Callout tone=Tone::Warning title="The server address is not known">
                    <p>{if asks { "Type how machines reach this server, or set public_address in Settings. Until then the commands say SERVER_ADDRESS." } else { "Set public_address in Settings, or replace SERVER_ADDRESS by hand." }}</p>
                    {children.map(|c| c())}
                </Callout>
            </div>
        }
    });
    let file_label = file.clone();
    let tabs = vec![
        ("commands", "Commands".to_string()),
        ("file", file_label),
        ("env", "Environment variable".to_string()),
    ];
    let allow_note = if kind == ClientEntry::ENTITY {
        "The allow list comes from the services that use this client."
    } else {
        "The forwards come from the private services this visitor may use."
    };
    view! {
        <div data-testid="snippets" data-kind=sn.kind.clone() data-name=sn.name.clone()>
            {unknown}
            <div class="mb-3 flex flex-wrap items-center gap-3">
                <burrow_ui_kit::PillTabs tabs=tabs active=tab on_change=Callback::new(move |t: &'static str| tab.set(t))/>
                <span class="ml-auto"></span>
                <Show when=move || tab.get() == "commands">
                    <Segmented
                        name="os"
                        options=vec![("linux".to_string(), "Linux".to_string(), false), ("macos".to_string(), "macOS".to_string(), false), ("windows".to_string(), "Windows".to_string(), false)]
                        value=os
                        on_change=move |v: String| os.set(v)
                        label="Operating system"
                    />
                </Show>
            </div>
            {move || match tab.get() {
                "commands" => view! {
                    <div data-testid="snippet-commands">
                        <p class="mb-2 flex flex-wrap items-center gap-x-2 gap-y-1 text-sm">
                            <a class="inline-flex items-center gap-1 font-semibold text-accent-ink underline underline-offset-2" href=RELEASES target="_blank" rel="noopener noreferrer" data-testid="download">
                                {move || format!("Download burrow for {}", os_label(&os.get()))}
                                <burrow_ui_kit::Icon name="external" small=true/>
                            </a>
                            <span class="text-text-muted">"and unpack it next to the config; the commands below run it from there."</span>
                        </p>
                        <CodeBlock text=commands_text/>
                        {has_init.then(|| view! { <p class="mt-2 text-xs text-text-muted">"burrow init prompts for the secret, so it stays out of your shell history."</p> })}
                    </div>
                }
                .into_any(),
                "env" => view! {
                    <div data-testid="snippet-env">
                        <CodeBlock text=env_config.clone() file_name=file.clone()/>
                        <p class="my-2 text-sm text-text-muted">"Keep the secret out of the file: set it in the environment of the service."</p>
                        <div class="space-y-2">
                            <CodeBlock text=export.clone()/>
                            <CodeBlock text=ps.clone()/>
                        </div>
                    </div>
                }
                .into_any(),
                _ => view! {
                    <div data-testid="snippet-file">
                        <CodeBlock text=config.clone() file_name=file.clone() testid="config-text"/>
                        <p class="mt-2 text-xs text-text-muted">{allow_note}</p>
                    </div>
                }
                .into_any(),
            }}
        </div>
    }
}

fn added_outside_edit(s: crate::store::Store, path: &[String]) {
    let entity: Vec<String> = path.iter().take(2).cloned().collect();
    if !s.edit.is_editing(&entity) {
        s.toast(Tone::Success, "Added to changes", Some("Review"));
    }
}

pub fn revealed_for(section: &str, name: &str) -> Option<Applied> {
    let e = store().edit;
    e.outcome.with(|o| match o {
        Some(crate::edit::Outcome::Applied(a))
            if a.secrets.iter().any(|s| {
                s.path.first().map(String::as_str) == Some(section)
                    && s.path.get(1).map(String::as_str) == Some(name)
            }) =>
        {
            Some(a.clone())
        }
        _ => None,
    })
}

#[component]
pub fn ShownOnce(section: String, name: String) -> impl IntoView {
    let s = store();
    let e = s.edit;
    let saved = RwSignal::new(false);
    let hidden = RwSignal::new(false);
    let (sec, nm) = (section.clone(), name.clone());
    let body = move || {
        let a = revealed_for(&sec, &nm)?;
        let sec_item = a
            .secrets
            .iter()
            .find(|x| x.path.first() == Some(&sec) && x.path.get(1) == Some(&nm))
            .cloned()?;
        let sn = a.snippets.iter().find(|x| x.name == nm).cloned();
        let what = if sec == ClientEntry::section() {
            "client.yaml"
        } else {
            "visitor.yaml"
        };
        let value = sec_item.value.clone();
        let shown = {
            let value = value.clone();
            Signal::derive(move || {
                if hidden.get() {
                    "•".repeat(32)
                } else {
                    value.clone()
                }
            })
        };
        let copy_value = value.clone();
        let note = format!(
            "Copy it or download {what} now. Afterwards you see only the fingerprint {}.",
            sec_item.fp
        );
        let nm2 = nm.clone();
        let (sec3, new_fp) = (sec.clone(), sec_item.fp.clone());
        let waiting = move || {
            let on = s.status.with(|st| {
                st.as_ref()
                    .and_then(|st| st.clients.iter().find(|c| c.name == nm2))
                    .filter(|c| c.connected)
                    .map(|c| c.from.clone().unwrap_or_default())
            });
            let used = in_use_fp(&sec3, &nm2);
            match on {
                Some(_) if used.as_ref().is_some_and(|u| *u != new_fp) => view! { <p class="mt-4 flex items-center gap-2 text-sm text-text-muted" data-testid="old-secret"><burrow_ui_kit::Spinner/>{format!("{} is still connected with its old secret; it switches once its config has the new one.", nm2)}</p> }.into_any(),
                Some(from) => view! { <p class="mt-4 flex items-center gap-2 text-sm text-success" data-testid="connected-now"><span class="size-2 rounded-full bg-success"></span>{format!("{} connected from {from}", nm2)}</p> }.into_any(),
                None => view! { <p class="mt-4 flex items-center gap-2 text-sm text-text-muted"><burrow_ui_kit::Spinner/>{format!("Waiting for {} to connect…", nm2)}</p> }.into_any(),
            }
        };
        let snippet = sn.map(|sn| view! { <SnippetView sn=sn secret=value.clone()/> });
        Some(view! {
            <div data-testid="shown-once">
                <div class="mb-4" data-testid="revealed" data-fp=sec_item.fp.clone()>
                    <Callout tone=Tone::Warning title="This is the only time the secret is shown.">
                        <p>{note}</p>
                    </Callout>
                </div>
                <label class="mb-1.5 block text-sm font-semibold" for="revealed-secret">"Secret"</label>
                <div class="mb-5 flex flex-wrap items-center gap-2">
                    <div class="flex h-[38px] min-w-0 flex-1 items-center rounded-input border border-border-strong bg-input px-2.5 font-mono text-[13px]" id="revealed-secret" data-testid="secret-value">
                        <pre class="truncate">{move || shown.get()}</pre>
                    </div>
                    <button type="button" class=burrow_ui_kit::button_class("primary", false) on:click=move |_| {
                        burrow_ui_kit::copy_text(&copy_value);
                        s.toast(Tone::Success, "Copied", None);
                    }>
                        <burrow_ui_kit::Icon name="copy" small=true/>
                        "Copy secret"
                    </button>
                    <button type="button" class=burrow_ui_kit::button_class("secondary", false) on:click=move |_| hidden.update(|h| *h = !*h)>
                        <burrow_ui_kit::Icon name="eye" small=true/>
                        {move || if hidden.get() { "Show" } else { "Hide" }}
                    </button>
                </div>
                {snippet}
                {(sec == ClientEntry::section()).then(|| waiting.clone())}
                <div class="sticky bottom-4 z-20 mt-6 flex items-center gap-3 rounded-card border border-border bg-surface px-4 py-3 shadow-overlay" data-sticky-bar="">
                    <label class="flex items-center gap-2 text-sm">
                        <input type="checkbox" data-testid="saved" class="size-4 accent-accent" prop:checked=move || saved.get() on:change:target=move |ev| saved.set(ev.target().checked())/>
                        "I have saved the secret"
                    </label>
                    <span class="ml-auto"></span>
                    <Button
                        label="Done"
                        variant="primary"
                        testid="close-shown-once"
                        disabled=Signal::derive(move || !saved.get())
                        reason=Signal::derive(move || if saved.get() { String::new() } else { "Tick I have saved the secret first".to_string() })
                        on_click=move |_| {
                            saved.set(false);
                            e.outcome.update(|o| {
                                if let Some(crate::edit::Outcome::Applied(a)) = o {
                                    a.secrets.clear();
                                    a.snippets.clear();
                                }
                            });
                        }
                    />
                </div>
            </div>
        })
    };
    view! { {body} }
}

#[component]
pub fn ConnectPanel(section: String, name: String) -> impl IntoView {
    let data: RwSignal<Option<Result<Snippets, String>>> = RwSignal::new(None);
    let address = RwSignal::new(String::new());
    let kind = if section == ClientEntry::section() {
        ClientEntry::ENTITY
    } else {
        VisitorEntry::ENTITY
    };
    let fetch = move |name: String, addr: Option<String>| {
        data.set(None);
        let body = api::body(&msg::ConnectInfo {
            kind: kind.to_string(),
            name,
            address: addr,
        });
        api::request(msg::req::CONNECT_INFO, body, move |r| {
            let _ = data.try_set(Some(r.map_err(|e| e.message).and_then(|v| {
                serde_json::from_value::<Snippets>(v).map_err(|e| e.to_string())
            })));
        });
    };
    let known = store().server_addr.get_untracked();
    if !known.is_empty() {
        address.set(known.clone());
    }
    fetch(name.clone(), (!known.is_empty()).then_some(known));
    let n2 = StoredValue::new(name.clone());
    let body = move || match data.get() {
        None => view! { <p class="text-text-muted">"Loading…"</p> }.into_any(),
        Some(Err(e)) => view! { <p class="text-danger">{e}</p> }.into_any(),
        Some(Ok(sn)) => {
            let known = sn.server_known;
            view! {
                <div>
                    <SnippetView sn=sn>
                        {(!known).then(|| view! {
                            <div class="mt-2 flex items-end gap-2">
                                <div class="flex-1">
                                    <label class="sr-only" for="connect-address">"Server address"</label>
                                    <TextInput id="connect-address" value=address on_input=move |t: String| address.set(t) placeholder="myserver.example.com" mono=true/>
                                </div>
                                <Button label="Use it" disabled=Signal::derive(move || address.with(|a| a.trim().is_empty())) reason=Signal::derive(move || if address.with(|a| a.trim().is_empty()) { "Type the server address first".to_string() } else { String::new() }) on_click=move |_| fetch(n2.get_value(), Some(address.get_untracked()))/>
                            </div>
                        })}
                    </SnippetView>
                    <p class="mt-2 text-sm text-text-muted">"The secret is not shown: it is set when the file is written by burrow init, or taken from the environment variable."</p>
                </div>
            }
            .into_any()
        }
    };
    view! { <div data-testid="connect">{body}</div> }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn secret_rows_show_fingerprints_sources_and_new_ones() {
        let v = json!([
            {"$secret": {"fp": "aaaa0001", "src": "literal"}},
            {"$secret": {"fp": null, "src": {"env": "HOME_SECRET"}, "unset": true}},
            {"$new_secret": {"handle": "h1", "fp": "bbbb0002"}}
        ]);
        let r = rows(Some(&v));
        assert_eq!(r.len(), 3);
        assert_eq!(r[0].source, "in server.yaml");
        assert!(r[1].unset);
        assert_eq!(r[1].source, "env: HOME_SECRET");
        assert!(r[2].fresh);
        assert_eq!(r[2].fp, "bbbb0002");
        assert!(rows(None).is_empty());
    }
}
