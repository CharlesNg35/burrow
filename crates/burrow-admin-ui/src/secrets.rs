#[derive(Debug, Clone, PartialEq)]
pub struct Row {
    pub fp: String,
    pub source: String,
    pub fresh: bool,
    pub unset: bool,
}

pub fn rows(v: Option<&Value>) -> Vec<Row> {
    let items: Vec<Value> = match v {
        Some(Value::Array(a)) => a.clone(),
        Some(other) => vec![other.clone()],
        None => Vec::new(),
    };
    items
        .iter()
        .filter_map(|i| {
            if let Some((_, fp)) = as_new_secret(i) {
                return Some(Row {
                    fp,
                    source: "new, generated by the server".into(),
                    fresh: true,
                    unset: false,
                });
            }
            let s = as_secret(i)?;
            Some(Row {
                fp: s.fp.clone().unwrap_or_default(),
                source: match &s.src {
                    SecretSrc::Literal => "in server.yaml".into(),
                    SecretSrc::Env(e) => format!("from environment variable {e}"),
                },
                fresh: false,
                unset: s.unset || s.fp.is_none(),
            })
        })
        .collect()
}

fn in_use_fp(section: &str, name: &str) -> Option<String> {
    if section != "clients" {
        return None;
    }
    store().state.with(|s| {
        s.as_ref()
            .and_then(|s| s.runtime.sessions.get(name))
            .map(|x| x.secret_fp.clone())
    })
}

pub fn secret_list(path: Path, id: String, max: u32) -> AnyView {
    let s = store();
    let e = s.edit;
    let section = path.first().cloned().unwrap_or_default();
    let name = path.get(1).cloned().unwrap_or_default();
    let p2 = path.clone();
    let list = Memo::new(move |_| rows(e.value(&p2).as_ref()));
    let (sec2, name2) = (section.clone(), name.clone());
    let in_use = Signal::derive(move || in_use_fp(&sec2, &name2));
    let p3 = path.clone();
    let add = move |_| {
        let p = p3.clone();
        api::request(msg::req::GENERATE_SECRET, json!({}), move |r| {
            if let Ok(Ok(g)) = r.map(serde_json::from_value::<GeneratedSecret>) {
                e.add_secret(&p, &g.handle, &g.fp);
            }
        });
    };
    let full = Signal::derive(move || list.with(|l| l.len() as u32 >= max.max(1)));
    let label = Signal::derive(move || {
        if list.with(Vec::is_empty) {
            "Generate a secret".to_string()
        } else {
            "Rotate: add a new secret".to_string()
        }
    });
    let p4 = path.clone();
    let body = move || {
        let used = in_use.get();
        list.get()
            .into_iter()
            .map(|r| {
                let fp = r.fp.clone();
                let using = used.as_deref() == Some(fp.as_str());
                let p = p4.clone();
                let only_one = list.with(|l| l.len() == 1);
                view! {
                    <li class="flex flex-wrap items-center gap-2 py-1" data-fp=fp.clone() data-in-use=using.then_some("true")>
                        <span class="font-mono text-sm">{format!("secret {fp}")}</span>
                        <span class="text-sm text-text-muted">{r.source.clone()}</span>
                        {r.unset.then(|| view! { <span class="text-sm text-danger">"not set in the environment"</span> })}
                        {using.then(|| view! { <span class="text-sm text-success" data-testid="in-use">"● in use by the current session"</span> })}
                        {(!only_one).then(|| {
                            let fp = fp.clone();
                            view! {
                                <button
                                    type="button"
                                    class=burrow_ui_kit::button_class("ghost", true)
                                    data-testid="remove-secret"
                                    aria-label=format!("Remove secret {fp}")
                                    on:click=move |_| e.remove_secret(&p, &fp)
                                >
                                    "Remove"
                                </button>
                            }
                        })}
                    </li>
                }
            })
            .collect_view()
    };
    view! {
        <div id=id data-testid="secrets">
            <ul>{body}</ul>
            <div class="mt-2">
                <Button
                    label=label
                    small=true
                    testid="rotate"
                    disabled=full
                    reason=Signal::derive(move || if full.get() { format!("at most {max} secrets") } else { String::new() })
                    on_click=add
                />
            </div>
            <p class="mt-1 text-sm text-text-muted">"Secret values are never shown here. A new one is shown once, after Apply."</p>
        </div>
    }
    .into_any()
}

fn os_now() -> String {
    let ua = window()
        .navigator()
        .user_agent()
        .unwrap_or_default()
        .to_lowercase();
    if ua.contains("windows") {
        "windows".into()
    } else if ua.contains("mac os") {
        "macos".into()
    } else {
        "linux".into()
    }
}

#[component]
pub fn SnippetView(sn: Snippets, #[prop(optional)] secret: Option<String>) -> impl IntoView {
    let tab = RwSignal::new("file");
    let os = RwSignal::new(os_now());
    let tabs = vec![
        ("file", sn.file_name.clone()),
        ("commands", "Commands".to_string()),
        ("env", "Environment variable".to_string()),
    ];
    let commands = sn.commands.clone();
    let commands_view = move || {
        let o = os.get();
        commands
            .iter()
            .filter(|c| c.os == o)
            .map(|c| {
                view! {
                    <div class="mb-2">
                        <p class="text-sm text-text-muted">{c.label.clone()}</p>
                        <CodeBlock text=c.line.clone()/>
                    </div>
                }
            })
            .collect_view()
    };
    let export = match &secret {
        Some(v) => format!("export {}='{v}'", sn.env_var),
        None => format!("export {}='…'", sn.env_var),
    };
    let ps = match &secret {
        Some(v) => format!("$env:{} = '{v}'", sn.env_var),
        None => format!("$env:{} = '…'", sn.env_var),
    };
    let config = sn.config.clone();
    let file = sn.file_name.clone();
    let env_config = sn.env_config.clone();
    let unknown = (!sn.server_known).then(|| {
        view! {
            <Callout tone=Tone::Warning title="The server address is not known">
                <p>"Set public_address in Settings, or replace SERVER_ADDRESS by hand."</p>
            </Callout>
        }
    });
    view! {
        <div data-testid="snippets" data-kind=sn.kind.clone() data-name=sn.name.clone()>
            {unknown}
            <Tabs tabs=tabs active=tab/>
            {move || match tab.get() {
                "commands" => view! {
                    <div data-testid="snippet-commands">
                        <div class="mb-2">
                            <Segmented
                                name="os"
                                options=vec![("linux".to_string(), "Linux".to_string(), false), ("macos".to_string(), "macOS".to_string(), false), ("windows".to_string(), "Windows".to_string(), false)]
                                value=os
                                on_change=move |v: String| os.set(v)
                                label="Operating system"
                            />
                        </div>
                        {commands_view.clone()}
                    </div>
                }
                .into_any(),
                "env" => view! {
                    <div data-testid="snippet-env">
                        <CodeBlock text=env_config.clone() file_name=file.clone()/>
                        <p class="my-2 text-sm text-text-muted">"Keep the secret out of the file: set it in the environment of the service."</p>
                        <CodeBlock text=export.clone()/>
                        <CodeBlock text=ps.clone()/>
                    </div>
                }
                .into_any(),
                _ => view! { <div data-testid="snippet-file"><CodeBlock text=config.clone() file_name=file.clone() testid="config-text"/></div> }.into_any(),
            }}
        </div>
    }
}

#[component]
pub fn ShownOnce() -> impl IntoView {
    let e = store().edit;
    let open = RwSignal::new(false);
    let shown: RwSignal<Option<Applied>> = RwSignal::new(None);
    Effect::new(move |_| {
        if let Some(crate::edit::Outcome::Applied(a)) = e.outcome.get()
            && !a.secrets.is_empty()
        {
            shown.set(Some(a));
            open.set(true);
        }
    });
    let saved = RwSignal::new(false);
    let body = move || {
        let a = shown.get()?;
        let panels = a
            .secrets
            .iter()
            .map(|sec| {
                let sn = a
                    .snippets
                    .iter()
                    .find(|s| sec.path.get(1) == Some(&s.name))
                    .cloned();
                let who = sec.path.get(..2).map(|p| p.join(" ")).unwrap_or_default();
                let value = sec.value.clone();
                let for_snippet = value.clone();
                let snippet = sn.map(move |sn| view! { <SnippetView sn=sn secret=for_snippet/> });
                view! {
                    <div class="mb-4" data-testid="revealed" data-fp=sec.fp.clone()>
                        <Callout tone=Tone::Warning title=format!("Shown once: the new secret of {who}")>
                            <p>"This is the only time the secret is shown. Copy it or download the file now."</p>
                            <CodeBlock text=value testid="secret-value"/>
                        </Callout>
                        {snippet}
                    </div>
                }
            })
            .collect_view();
        Some(view! {
            <div>
                {panels}
                <label class="flex items-center gap-2">
                    <input type="checkbox" data-testid="saved" prop:checked=move || saved.get() on:change:target=move |ev| saved.set(ev.target().checked())/>
                    "I have saved the secret"
                </label>
                <div class="mt-3 flex justify-end">
                    <Button
                        label="Close"
                        variant="primary"
                        testid="close-shown-once"
                        disabled=Signal::derive(move || !saved.get())
                        on_click=move |_| {
                            open.set(false);
                            saved.set(false);
                            shown.set(None);
                            e.outcome.update(|o| {
                                if let Some(crate::edit::Outcome::Applied(a)) = o {
                                    a.secrets.clear();
                                    a.snippets.clear();
                                }
                            });
                        }
                    />
                </div>
            </div>
        })
    };
    view! {
        <Dialog open=open title="Connect the new machine" testid="shown-once" dismissable=false>
            {body}
        </Dialog>
    }
}

#[component]
pub fn ConnectPanel(section: String, name: String) -> impl IntoView {
    let data: RwSignal<Option<Result<Snippets, String>>> = RwSignal::new(None);
    let address = RwSignal::new(String::new());
    let kind = if section == "clients" {
        "client"
    } else {
        "visitor"
    };
    let fetch = move |name: String, addr: Option<String>| {
        data.set(None);
        let body = json!({ "kind": kind, "name": name, "address": addr });
        api::request(msg::req::CONNECT_INFO, body, move |r| {
            let _ = data.try_set(Some(r.map_err(|e| e.message).and_then(|v| {
                serde_json::from_value::<Snippets>(v).map_err(|e| e.to_string())
            })));
        });
    };
    fetch(name.clone(), None);
    let n2 = StoredValue::new(name.clone());
    let body = move || match data.get() {
        None => view! { <p class="text-text-muted">"Loading…"</p> }.into_any(),
        Some(Err(e)) => view! { <p class="text-danger">{e}</p> }.into_any(),
        Some(Ok(sn)) => {
            let ask = (!sn.server_known).then(|| {
                view! {
                    <div class="mb-3 flex items-end gap-2">
                        <div class="flex-1">
                            <label class="text-sm" for="connect-address">"How do machines reach this server?"</label>
                            <TextInput id="connect-address" value=address on_input=move |t: String| address.set(t) placeholder="myserver.example.com" mono=true/>
                        </div>
                        <Button label="Use it" small=true on_click=move |_| fetch(n2.get_value(), Some(address.get_untracked()))/>
                    </div>
                }
            });
            view! {
                <div>
                    {ask}
                    <SnippetView sn=sn/>
                    <p class="mt-2 text-sm text-text-muted">"The secret is not shown: it is set when the file is written by burrow init, or taken from the environment variable."</p>
                </div>
            }
            .into_any()
        }
    };
    view! { <div data-testid="connect">{body}</div> }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn secret_rows_show_fingerprints_sources_and_new_ones() {
        let v = json!([
            {"$secret": {"fp": "aaaa0001", "src": "literal"}},
            {"$secret": {"fp": null, "src": {"env": "HOME_SECRET"}, "unset": true}},
            {"$new_secret": {"handle": "h1", "fp": "bbbb0002"}}
        ]);
        let r = rows(Some(&v));
        assert_eq!(r.len(), 3);
        assert_eq!(r[0].source, "in server.yaml");
        assert!(r[1].unset);
        assert!(r[1].source.contains("HOME_SECRET"));
        assert!(r[2].fresh);
        assert_eq!(r[2].fp, "bbbb0002");
        assert!(rows(None).is_empty());
    }
}
