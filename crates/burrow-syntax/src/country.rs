pub fn name_of(code: &str) -> Option<&'static str> {
    COUNTRIES
        .binary_search_by(|(c, _)| (*c).cmp(code))
        .ok()
        .map(|i| COUNTRIES[i].1)
}

pub fn country(text: &str) -> Result<String, String> {
    let code = text.trim().to_ascii_uppercase();
    if code.is_empty() {
        return Err("a country code is required".into());
    }
    if name_of(&code).is_some() {
        return Ok(code);
    }
    let wanted = text.trim().to_lowercase();
    match COUNTRIES.iter().find(|(_, n)| n.to_lowercase() == wanted) {
        Some((c, n)) => Err(format!("use the two-letter code {c} for {n}")),
        None => Err(format!(
            "\"{}\" is not a two-letter ISO 3166 country code, for example FR, DE or US",
            text.trim()
        )),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_unique_for_lookups() {
        assert!(COUNTRIES.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(
            COUNTRIES
                .iter()
                .all(|(c, _)| c.len() == 2 && c.bytes().all(|b| b.is_ascii_uppercase()))
        );
    }

    #[test]
    fn codes_are_kept_upper_case_and_names_point_at_their_code() {
        assert_eq!(country(" fr ").unwrap(), "FR");
        assert_eq!(country("XK").unwrap(), "XK");
        assert_eq!(name_of("CH"), Some("Switzerland"));
        assert!(country("France").unwrap_err().contains("FR"));
        assert!(country("ZZ").unwrap_err().contains("ISO 3166"));
        assert!(country("").unwrap_err().contains("required"));
    }
}
