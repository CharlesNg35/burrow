import json
import os
import platform
import subprocess
import sys
from pathlib import Path

run = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
rows = [json.loads(line) for line in (run / "results.jsonl").read_text().splitlines() if line.strip()]
tools = list(dict.fromkeys(r["tool"] for r in rows))
by = {(r["tool"], r["test"]): r["result"] for r in rows}


def sh(cmd):
    try:
        return subprocess.run(cmd, shell=True, capture_output=True, text=True).stdout.strip()
    except OSError:
        return ""


def cell(tool, test, key, fmt="{}"):
    v = by.get((tool, test), {}).get(key)
    return "-" if v is None else fmt.format(v)


def idle(tool, n):
    r = by.get((tool, f"idle_{n}"))
    if not r:
        return "-"
    delta = (r["rss_after_kib"] - r["rss_before_kib"]) / 1024
    return f"{r['rss_after_kib'] / 1024:.1f} MiB (+{delta:.1f}, {r['open']} open)"


labels = {
    "direct": "direct (no tunnel)",
    "burrow": "burrow (Noise ChaChaPoly, default)",
    "burrow-aesgcm": "burrow (Noise AES-GCM)",
    "burrow-plaintext": "burrow (insecure_plaintext)",
    "burrow-ws": "burrow over WebSocket (ws://, ChaChaPoly)",
    "rathole": "rathole 0.5.0 (tcp, no encryption)",
    "rathole-noise": "rathole 0.5.0 (noise NK ChaChaPoly)",
    "frp": "frp 0.71.1 (default: TLS, tcpMux)",
    "frp-plain": "frp 0.71.1 (tls disabled, tcpMux)",
    "frp-nomux": "frp 0.71.1 (TLS, tcpMux disabled)",
    "chisel": "chisel 1.12.0 (SSH over WebSocket)",
}

cpu = sh("lscpu | sed -n 's/^Model name:[ ]*//p' | head -1")
out = []
out.append("# Benchmarks\n")
out.append("Generated by `bench/run.sh`; do not edit by hand. Raw results: `results.jsonl` in the run directory.\n")
out.append("## Machine\n")
out.append(f"- CPU: {cpu} ({os.cpu_count()} logical CPUs)")
mem_gib = os.sysconf("SC_PAGE_SIZE") * os.sysconf("SC_PHYS_PAGES") / (1 << 30)
out.append(f"- Memory: {mem_gib:.0f} GiB")
out.append(f"- Kernel: {platform.system()} {platform.release()}")
out.append(f"- Rust: {sh('rustc --version')}")
out.append(f"- iperf3: {sh('iperf3 --version | head -1')}")
out.append(f"- Run: `{run.name}`, everything on loopback (127.0.0.1); the tunnel server, tunnel client, echo and iperf3 servers and load generator share the machine.\n")
out.append("## Throughput and latency\n")
out.append("| setup | iperf3 1 stream | iperf3 4 streams | latency p50 | latency p99 | p99 under load | new conns/s |")
out.append("|---|---|---|---|---|---|---|")
for t in tools:
    out.append(
        f"| {labels.get(t, t)} | {cell(t, 'throughput_p1', 'gbit_per_sec', '{} Gbit/s')} | {cell(t, 'throughput_p4', 'gbit_per_sec', '{} Gbit/s')} "
        f"| {cell(t, 'latency', 'p50_us', '{} µs')} | {cell(t, 'latency', 'p99_us', '{} µs')} "
        f"| {cell(t, 'latency_under_load', 'p99_us', '{} µs')} | {cell(t, 'connrate', 'conn_per_sec')} |"
    )
out.append("")
out.append("## Memory with idle connections\n")
out.append("RSS of the tunnel server plus the tunnel client after N idle connections are open through the tunnel (change from the connected-but-idle baseline in brackets).\n")
counts = sorted({int(k[1].split("_")[1]) for k in by if k[1].startswith("idle_")})
out.append("| setup | " + " | ".join(f"{n} idle connections" for n in counts) + " |")
out.append("|---|" + "---|" * len(counts))
for t in tools:
    if t == "direct":
        continue
    out.append(f"| {labels.get(t, t)} | " + " | ".join(idle(t, n) for n in counts) + " |")
out.append("")
out.append("## Method\n")
out.append("```sh")
out.append("bench/fetch.sh          # downloads pinned rathole, frp and chisel releases and checks their sha256")
out.append("bench/run.sh            # builds burrow, runs every setup, writes this file")
out.append("TOOLS='burrow rathole' IDLE_COUNTS=1000 bench/run.sh   # subset")
out.append("```\n")
out.append("- throughput: `iperf3 -c 127.0.0.1 -p <tunnel port> -t 10 -P 1` and `-P 4`, received bits per second.")
out.append("- latency: one TCP connection, 20000 sequential 64-byte echo round trips (`loadgen latency`), after 200 warm-up round trips.")
out.append("- p99 under load: the same latency test (5000 round trips) while `iperf3 -P 4 -b 500M` (2 Gbit/s in total, a rate every setup sustains) runs through a second service of the same tunnel; this exposes head-of-line blocking in multiplexed designs without turning into a CPU-saturation contest.")
out.append("- new connections per second: 32 workers, each opening a new connection, doing one 16-byte echo and closing, for 10 s (`loadgen connrate`).")
out.append("- memory: `loadgen idle --count N` opens N connections through the tunnel, echoes 4 bytes on each, then holds them; RSS is read from `/proc/<pid>/status` 3 s later.")
notes = root / "bench" / "notes.md"
if notes.exists():
    out.append("")
    out.append(notes.read_text().strip())
print("\n".join(out))
